export function route(
  start: Definition<string>,
  ...elements: readonly ((value: never) => unknown)[]
): unknown {
  let zero: RouteZero = {
    ...start,
    methods: ["help"],
    params: {},
    children: [],
  };

  return elements.reduce<unknown>(
    (value, element) => element(value as never),
    zero,
  );
}

