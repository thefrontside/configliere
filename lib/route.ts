export function routes<const C extends readonly AnyRoute[]>(
  ...children: C
): <R extends AnyRoute>(
  route: R,
) => Route<
  R["name"],
  MethodsOf<R>,
  ModelOf<R>,
  readonly [...R["children"], ...C]
> {
  return <R extends AnyRoute>(route: R) => {
    type Output = Route<
      R["name"],
      MethodsOf<R>,
      ModelOf<R>,
      readonly [...R["children"], ...C]
    >;

    return {
      ...route,
      children: [
        ...route.children,
        ...children,
      ] as unknown as Output["children"],
      params: route.params as Output["params"],
    };
  };
}
